#!/usr/bin/env python3
"""
Writes the paper's LaTeX tables into tables_out/ from data/derived.

Emits table_agreement.tex (total words, number of different words, type-token ratio) and
table_pipeline_wer.tex (Table 3: overall WER and its insertion/deletion/substitution split per
pipeline). The supplementary tables come from make_supp_tables.py.
"""
import csv, math, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from make_paper_figures import load, series, PUBLISHED   # reuse the validated loaders

OUT = os.path.join(ROOT, "tables_out"); os.makedirs(OUT, exist_ok=True)

def fit(x, y):
    n=len(x); mx=x.mean(); my=y.mean()
    sxx=((x-mx)**2).sum(); syy=((y-my)**2).sum(); sxy=((x-mx)*(y-my)).sum()
    return sxy/math.sqrt(sxx*syy), sxy/sxx, n

def ttr_series(data, spk, lang):
    import numpy as np
    xs, ys = [], []
    for r in data["types"]:
        if r["speaker"] != spk: continue
        ht, at = float(r[f"human_{lang}_tokens"]), float(r[f"vtc2_{lang}_tokens"])
        hy, ay = float(r[f"human_{lang}_types"]),  float(r[f"vtc2_{lang}_types"])
        if ht > 0 and at > 0: xs.append(hy/ht); ys.append(ay/at)
    return np.array(xs), np.array(ys)

def row(data, measure, spk):
    cells = []
    for lang in ("en", "es"):
        if measure == "ttr":
            x, y = ttr_series(data, spk, lang)
        else:
            x, y, _, _ = series(data, spk, lang, measure)
        r, s, n = fit(x, y)
        cells += [f"{r:.2f}".lstrip("0"), f"{s:.2f}", str(n)]
    return cells

# ---------------------------------------------------------------- Table 3
XL = os.path.join(ROOT, "data", "derived", "wer_per_recording_14clips.xlsx")
PAIRWISE = os.path.join(ROOT, "data", "derived", "supp_pairwise.csv")
# (workbook block, label in the paper, short name in supp_pairwise.csv), in table order
WER_ROWS = [("Only Whisper",          "WhisperX-VAD + VTC1 (post-hoc)", "WhisperX"),
            ("WhisperX-VAD + VTC2",   "WhisperX-VAD + VTC2 (post-hoc)", "WhisperX-VTC2"),
            ("VTC1 + Whisper",        "VTC1 + WhisperX",                "VTC1"),
            ("VTC2 + Whisper",        "VTC2 + WhisperX",                "VTC2"),
            ("Human-TS + Whisper",    "Human-TS + WhisperX (control)",  "HumanTS")]
CAPTION_WER = r"""\caption{Overall word error rate for each pipeline, scored on the whole transcript of each clip regardless of who was speaking, and split into insertions, deletions, and substitutions (each as a percentage of the words in the human transcript; the three sum to the overall rate, up to rounding). All pipelines transcribe with WhisperX large-v3 and discard output in languages other than English and Spanish. Values are averages over the 14 recordings, computed on the 157 scored clips. Rates can exceed 100\% because insertions count as errors but do not add to the human word count. For the two post-hoc pipelines, words the classifier credited to no speaker are not scored. Bold marks the lowest overall rate; it does not differ significantly from VTC2 + WhisperX ($p = {p}$). Error rates by speaker, which decided the choice of pipeline, together with confidence intervals, pairwise tests, and the VTC2-NoLang + WhisperX condition, are in the supplementary material (Tables~\ref{tab:supp-wer}--\ref{tab:supp-pairwise-overall}).}"""

def pipeline_wer():
    """Macro-average (over recordings) of the OVERALL sheet's insertion, deletion,
    substitution and WER columns, as percentages."""
    import openpyxl
    rows = list(openpyxl.load_workbook(XL, read_only=True, data_only=True)["OVERALL"]
                .iter_rows(values_only=True))
    top, hdr = rows[1], rows[2]
    out = {}
    for block, _, _ in WER_ROWS:
        c0 = top.index(block)
        col = {hdr[j]: j for j in range(c0, c0 + 14)}
        recs = [r for r in rows[3:] if r and isinstance(r[0], str) and r[0].startswith("P")
                and isinstance(r[col["WER"]], (int, float))]
        assert len(recs) == 14, (block, len(recs))
        out[block] = [100 * sum(r[col[k]] for r in recs) / len(recs)
                      for k in ("Insertions %", "Deletions %", "Substitutions %", "WER")]
    return out

def table_pipeline_wer():
    v = pipeline_wer()
    best = min(WER_ROWS, key=lambda w: v[w[0]][3])
    # the caption reports how the lowest-WER pipeline compares with VTC2 + WhisperX
    pw = {(r["stratum"], r["pipe_a"], r["pipe_b"]): r for r in csv.DictReader(open(PAIRWISE, encoding="utf-8-sig"))}
    a, b = best[2], "VTC2"
    r = pw.get(("OVERALL", a, b)) or pw[("OVERALL", b, a)]
    p = f"{float(r['p']):.2f}".lstrip("0")
    assert not r["stars"], "caption says the lowest pipeline does not differ from VTC2 + WhisperX"
    L = ["% Generated by stage3_tables_figures/make_tables.py -- do not edit by hand.",
         r"\begin{table}", r"\centering", CAPTION_WER.replace("{p}", p),
         r"\label{tab:pipeline-wer}", "", r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{lrrrr}",
         r"\toprule", r"& Insertions & Deletions & Substitutions & Overall \\",
         r"Pipeline & (\%) & (\%) & (\%) & WER (\%) \\", r"\midrule"]
    for block, label, _ in WER_ROWS:
        i, d, s, w = v[block]
        wtxt = f"{w:.1f}"
        if block == best[0]: wtxt = r"\textbf{" + wtxt + "}"
        L += [label, f"& {i:.1f} & {d:.1f} & {s:.1f} & {wtxt} " + r"\\", ""]
    L += [r"\bottomrule", r"\end{tabular}%", "}", r"\end{table}"]
    p_out = os.path.join(OUT, "table_pipeline_wer.tex")
    open(p_out, "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {p_out}")

def main():
    data = load()
    L = ["% Generated by stage3_tables_figures/make_tables.py -- do not edit by hand.",
         r"\begin{table}[t]", r"\centering",
         r"\caption{Clip-level agreement between automated and manual counts for VTC2~+~WhisperX. "
         r"$r$ is the Pearson correlation and slope the ordinary least-squares coefficient of automated "
         r"on manual values; $n$ is the number of clips entering the fit. Type--token ratio is reported "
         r"for comparability with \citet{tang2025}; it is computed only on clips where both transcripts "
         r"contain at least one word in that language, which is why its $n$ is slightly smaller.}",
         r"\label{tab:agreement}", r"\begin{tabular}{llrrrrrr}", r"\toprule",
         r" & & \multicolumn{3}{c}{English} & \multicolumn{3}{c}{Spanish} \\",
         r"\cmidrule(lr){3-5} \cmidrule(lr){6-8}",
         r"Measure & Speaker & $r$ & Slope & $n$ & $r$ & Slope & $n$ \\", r"\midrule"]
    for label, measure in (("Total words", "tokens"), ("Number of different words", "types"),
                           ("Type--token ratio", "ttr")):
        for i, (spk, nice) in enumerate((("adult", "Adults"), ("kchild", "Key child"))):
            lead = label if i == 0 else ""
            L.append(f"{lead} & {nice} & " + " & ".join(row(data, measure, spk)) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    p = os.path.join(OUT, "table_agreement.tex")
    open(p, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"wrote {p}")
    table_pipeline_wer()

if __name__ == "__main__":
    main()
